// The narration → public/vo/<id>.mp3 and voice.ts (when each phrase starts), with ElevenLabs.
//
//   ELEVENLABS_API_KEY=… node scripts/tts.ts [--align] [voice id] [segment ids…]     (needs ffmpeg)
//
// The clips and voice.ts are committed, so the film renders without a key. Run it again only when
// narration.ts changes; with segment ids it redoes just those. `--align` keeps the clips and only
// measures them again.
//
// Two requests per segment: speech (eleven_v3 reads mixed Chinese and English clearly, but has no
// speed setting and its own timestamps are rough), then forced alignment of the finished clip
// against the text, which is where the phrase times come from.

import { spawnSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

import { NARRATION, said } from "../narration.ts";

const key = process.env.ELEVENLABS_API_KEY;
if (!key) throw new Error("ELEVENLABS_API_KEY is not set");
const args = process.argv.slice(2);
const alignOnly = args[0] === "--align" && Boolean(args.shift());
const voice = args[0] && !NARRATION.some((s) => s.id === args[0]) ? args.shift()! : "MI36FIkp9wRP7cpWKPTl";
const only = new Set(args);
/** The clip is played this much faster, at the same pitch. */
const TEMPO = Number(process.env.VO_TEMPO ?? 1.12);
const API = "https://api.elevenlabs.io/v1";

const clip = (id: string) => fileURLToPath(new URL(`../public/vo/${id}.mp3`, import.meta.url));
const timesFile = new URL("../voice.json", import.meta.url);
type Times = { dur: number; len: number; t: number[][]; end: number[] };
const times: Record<string, Times> = existsSync(timesFile) ? JSON.parse(readFileSync(timesFile, "utf8")) : {};

const text = (i: number) => NARRATION[i]!.lines.map((l) => l.map(said).join("")).join("");

async function speak(id: string, words: string) {
  const r = await fetch(`${API}/text-to-speech/${voice}?output_format=mp3_44100_128`, {
    method: "POST",
    headers: { "xi-api-key": key!, "Content-Type": "application/json" },
    body: JSON.stringify({ text: words, model_id: "eleven_v3", voice_settings: { stability: 0.5 }, seed: 101 }),
  });
  if (!r.ok) throw new Error(`${id}: speech ${r.status} ${(await r.text()).slice(0, 300)}`);
  const ff = spawnSync("ffmpeg", ["-loglevel", "error", "-y", "-i", "pipe:0", "-filter:a", `atempo=${TEMPO}`, "-ac", "1", "-b:a", "128k", clip(id)], {
    input: Buffer.from(await r.arrayBuffer()),
  });
  if (ff.status !== 0) throw new Error(`${id}: ffmpeg ${ff.stderr}`);
}

async function align(id: string, words: string) {
  const form = new FormData();
  form.set("file", new Blob([readFileSync(clip(id))], { type: "audio/mpeg" }), `${id}.mp3`);
  form.set("text", words);
  const r = await fetch(`${API}/forced-alignment`, { method: "POST", headers: { "xi-api-key": key! }, body: form });
  if (!r.ok) throw new Error(`${id}: alignment ${r.status} ${(await r.text()).slice(0, 300)}`);
  const { characters } = (await r.json()) as { characters: { text: string; start: number; end: number }[] };
  if (characters.map((c) => c.text).join("") !== words) throw new Error(`${id}: the alignment is not the text that was sent`);
  return characters;
}

for (const [i, seg] of NARRATION.entries()) {
  if (only.size && !only.has(seg.id)) continue;
  if (!alignOnly) await speak(seg.id, text(i));
  const chars = await align(seg.id, text(i));

  // A phrase starts where its first character does; a line ends where its last one does.
  let at = 0;
  const t: number[][] = [];
  const end: number[] = [];
  for (const line of seg.lines) {
    const starts: number[] = [];
    for (const p of line) {
      starts.push(+chars[at]!.start.toFixed(2));
      at += [...said(p)].length;
    }
    t.push(starts);
    end.push(+chars[at - 1]!.end.toFixed(2));
  }
  // len is the whole clip, with the breath after the last word: the next clip waits for it.
  const probe = spawnSync("ffprobe", ["-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", clip(seg.id)], { encoding: "utf8" });
  times[seg.id] = { dur: end.at(-1)!, len: +Number(probe.stdout).toFixed(2), t, end };
  console.log(seg.id.padEnd(8), `${times[seg.id]!.dur}s`, JSON.stringify(t));
}

writeFileSync(timesFile, JSON.stringify(times, null, 1));
writeFileSync(
  new URL("../voice.ts", import.meta.url),
  `// Generated by scripts/tts.ts (forced alignment of each clip against its text); not hand-edited.
// Per segment: dur = when the last word ends; len = the length of the clip; t[line][phrase] = when that phrase starts; end[line] =
// when the line ends. All in seconds from the start of the clip (public/vo/<id>.mp3).
export const VOICE: Record<string, { dur: number; len: number; t: readonly (readonly number[])[]; end: readonly number[] }> = {
${NARRATION.map((s) => `  ${s.id}: ${JSON.stringify(times[s.id])},`).join("\n")}
};
`,
);
console.log(`total speech ${NARRATION.reduce((n, s) => n + (times[s.id]?.dur ?? 0), 0).toFixed(1)}s`);
